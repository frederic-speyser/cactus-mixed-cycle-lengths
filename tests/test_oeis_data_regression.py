def test_oeis_block_indexed_data_unchanged():
    for omega, expected in EXPECTED.items():
        rooted, unrooted = compute(omega, TERMS)
        # rooted[0] is the trivial a(0)=1, not shown in the OEIS fiches
        rooted_25 = rooted[1:TERMS + 1]
        unrooted_25 = unrooted[:TERMS]
        assert rooted_25 == expected['rooted'], f"Omega={omega}: rooted (block-indexed) sequence changed"
        assert unrooted_25 == expected['unrooted'], f"Omega={omega}: unrooted (block-indexed) sequence changed"


if __name__ == "__main__":
    test_oeis_block_indexed_data_unchanged()
    print(f"All {len(EXPECTED) * 2} OEIS-submission (block-indexed) sequences reproduced exactly.")
